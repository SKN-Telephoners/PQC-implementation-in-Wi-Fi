#ifndef PQC_SM_H
#define PQC_SM_H

#include "../utils/common.h"
#include "../src/common/pqc_help.h"

/*
* main struct used in PQC implementation (STA)
*/
struct wpa_pqc_sm {
    struct wpa_supplicant *wpa_s; // main context

    // config and negotiation
    u8 pqc_choice; // algorithm
    int pqc_enabled; // if PQC is used

    // PAKE
    u8 K_aes[AES_KEY_LEN]; // derived before PAKE-1
    u8 id[16]; // random
    u8 pwd[128]; // Wi-Fi password
    size_t pwd_len; // TODO: it needs to be read from config file 

    u8 *fsid; // counted before sending PAKE-3
    size_t fsid_len; 

    u8 s[PQC_R_LEN]; // from Feistel Network
    u8 *T;
    size_t T_len; 

    /* ML-KEM */
    u8 *ap_kem_public_key;  // pk: public key from AP (from Probe Response)
    size_t ap_kem_pub_len;

    u8 *kem_secret_key; // ssk: secret key (STA) needed for PAKE-4, generated before sending PAKE-3
    size_t kem_secret_key_len;
    u8 *sta_kem_public_key; // psk: public key STA (send in PAKE-3 as Z)
    size_t sta_kem_pub_len;

    u8 *sta_second_secret_key; // seck: secret key (STA) generated after association response
    size_t sta_second_secret_len; 
    u8 *sta_second_pub_key; //pubk: public key (STA) generated after association response
    size_t sta_second_pub_len;


    u8 *ap_ciphertext_2; // ciphertext generated by AP during KEM encapsulation - pubk
    size_t ap_ciphertext_2_len;

    u8 *shared_secret_K;       /* K - derived after encapsulation */
    size_t shared_secret_K_len;

    // ML-DSA from AP only
    u8 *dsa_public_key;     
    size_t dsa_keys_len;

    /* PASN-2 received materials */
    u8 *pasn_ciphertext;       /* ML-KEM ciphertext received from AP */
    size_t pasn_ciphertext_len;
    u8 *pasn_dsa_signature;    /* ML-DSA signature received from AP */
    size_t pasn_dsa_signature_len;
    u8 pasn_mic1[MIC_LEN];          /* MIC1 received from AP */
    u8 pasn_mic2[MIC_LEN];           /* MIC 2 generated during PARSING OF PASN2*/

    /* PASN derived materials */
    u8 *pasn_shared_secret;    /* PQC shared secret from ML-KEM decapsulation */
    size_t pasn_shared_secret_len;
    u8 pasn_ptk[PTK_LEN];           /* PTK - Pairwise Transient Key */
    u8 pasn_kek[KEK_LEN];           /* Key Encryption Key */
    u8 pasn_kck[KCK_LEN];           /* Key Confirmation Key */
    u8 pasn_tk[TK_LEN];            /* Temporal Key */

    u8 pmk[PMK_LEN];                /* PMK derived from PAKE, used for PASN PTK derivation */
    u8 ap_mac[ETH_ALEN];       /* AP MAC resolved at PAKE-1 time, used for fsid */

    struct wpabuf *rx_reassembly_buf; // for fragmentation purposes 
};
struct wpa_pqc_sm * pqc_sm_init(struct wpa_supplicant *wpa_s, struct wpa_ssid *ssid);
void pqc_sm_deinit(struct wpa_pqc_sm *sm);
int pqc_sm_rx_auth_req(struct wpa_pqc_sm *sm);
int pqc_sm_assoc_success(struct wpa_pqc_sm *sm);

#endif 